#!/usr/bin/env python3
"""Keep the rolling doc histories readable without loading them whole.

The decisions (`docs/decisions/CATEGORY.md`, one file per category, D258) and
`docs/roadmap.md` are append-only histories: they grow forever and they
contradict themselves, because a later entry is allowed to reverse an earlier
one. This tool derives the two summaries from them, so the summaries cannot
drift, and reports what still needs a human verdict.

    fe_docs.py build          rewrite docs/decisions-summary.md and
                              docs/roadmap-summary.md from the histories, and
                              .claude/skills from .agents/skills (D252)
    fe_docs.py check          exit 1 when a summary or a skill copy is stale
                              or an entry's status is missing or points
                              nowhere; `--strict` also fails while any entry
                              is still unreviewed
    fe_docs.py status         print the cleanup queue, always exit 0
    fe_docs.py queue          both queues numbered -- unreviewed entries and
                              the open gaps of shipping versions (see /triage)
    fe_docs.py show D64 V58   print those entries and nothing else
    fe_docs.py show D60..D64  print a range
    fe_docs.py category       the categories, each with its counts and scope
    fe_docs.py category lighting   that category's timeline: every entry in
                              order with its status, what was tried and what holds
    fe_docs.py new lighting "Title"   append an entry with the next free
                              number to that category's file, print where
    fe_docs.py file D64 rendering     move an entry to another category

Every entry in a history carries one line under its heading:

    **Status:** active
    **Status:** superseded by D26 -- the proxy hull and depth peel are removed
    **Status:** amended by D68
    **Status:** stopped
    **Status:** historical
    **Status:** unreviewed -- shaders are Slang now; no entry records the change

`active` is the current rule. `superseded by X` means X replaced it whole,
`amended by X` that X changed part of it and both still apply. `stopped` is an
attempt that was abandoned and is kept so it is not retried. `historical` was
true once and nothing replaced it. `unreviewed` is the cleanup queue: nobody has
decided yet, and `check` fails until someone does.
"""

